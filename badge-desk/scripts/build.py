"""Build the checked-in Pages Function module from the badge desk sources.

The portfolio's existing Pages project has no build command. Keeping the generated
module in Git therefore preserves that deployment configuration. Install the one
build dependency from requirements-build.txt before regenerating.
"""
import base64
import io
import json
import sys
import zipfile
from pathlib import Path

import qrcode
from qrcode.image.svg import SvgPathImage

root = Path(__file__).resolve().parents[1]
src = root / "src"
output = root.parent / "functions/_shared/badge-desk.generated.js"
config = json.loads((src / "badges.json").read_text())


def encode(data):
    return base64.b64encode(data).decode("ascii")


def qr_svg(url):
    code = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=4, box_size=10)
    code.add_data(url)
    code.make(fit=True)
    image = code.make_image(image_factory=SvgPathImage, fill_color="black", back_color="white")
    result = io.BytesIO()
    image.save(result)
    return result.getvalue()


assets = {}
for logo in sorted((src / "logos").glob("*.png")):
    assets[f"/logo/{logo.stem}.png"] = ("image/png", encode(logo.read_bytes()))
for group in config["groups"]:
    for number in range(1, group["count"] + 1):
        slug = f'{group["prefix"].lower()}-{number:02}'
        assets[f"/qr/{slug}.svg"] = ("image/svg+xml", encode(qr_svg(f'{config["origin"]}/b/{slug}')))
for filename, mime in [("site.css", "text/css"), ("app.js", "text/javascript"), ("index.html", "text/html")]:
    contents = (src / filename).read_text().replace("__BADGE_BASE_PATH__", "/badges")
    assets[f"/{filename}"] = (mime, encode(contents.encode()))

workbook = src / "activity-log.xlsx"
assets["/activity-log.xlsx"] = ("application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", encode(workbook.read_bytes()))
with zipfile.ZipFile(workbook) as archive:
    workbook_parts = {name: archive.read(name).decode("utf-8") for name in archive.namelist() if not name.endswith("/")}
jszip = (src / "vendor/jszip.min.js").read_text()
result = (
    "// Generated by badge-desk/scripts/build.py. Do not edit this file directly.\n"
    + f"const config = {json.dumps(config, separators=(',', ':'))};\n"
    + f"const assets = {json.dumps(assets, separators=(',', ':'))};\n"
    + f"const workbookParts = {json.dumps(workbook_parts, separators=(',', ':'))};\n"
    + "const JSZip = (() => { const module = {exports:{}}; const exports = module.exports;\n"
    + jszip + "\nreturn module.exports; })();\n"
    + (src / "activity-export.js").read_text() + "\n"
    + (src / "worker.js").read_text()
)
if "--check" in sys.argv:
    if not output.exists() or output.read_text() != result:
        raise SystemExit("Generated badge desk module is stale; run python badge-desk/scripts/build.py")
    print("Generated badge desk module is up to date")
else:
    output.write_text(result)
    print(f"Wrote {output.relative_to(root.parent)}")
